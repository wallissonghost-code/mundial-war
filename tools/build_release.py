"""Reproducibly assemble both standalone deliverables from checked-in sources."""
from pathlib import Path
import json,runpy
root=Path(__file__).resolve().parents[1]
runpy.run_path(str(root/'tools/generate_terrain.py'))
data=json.loads((root/'data/reference-mask.json').read_text())
w,h=data['width'],data['height']
assert len(data['rows'])==h and all(len(r)==w and set(r)<=set('01') for r in data['rows'])
assert len(data['regionRows'])==h and all(len(r)==w*3 for r in data['regionRows'])
header='''-- Mundial War 0.7.1 · generated by tools/build_release.py
local Players=game:GetService("Players")
local RS=game:GetService("ReplicatedStorage")
local remote=Instance.new("RemoteEvent")
remote.Name="MundialWar"
remote.Parent=RS
local cooldown={}
'''
header+=f'local W,H={w},{h}\n'
for key,name in [('rows','landRows'),('regionRows','regionRows'),('terrainRows','terrainRows')]:
    header+='local '+name+'={\n'+',\n'.join(json.dumps(r) for r in data[key])+'\n}\n'
(root/'src/server.server.lua').write_text(header+(root/'engine/core.lua').read_text()+'\n'+(root/'engine/server_adapter.lua').read_text())
html=(root/'web/template.html').read_text().replace('__MAP__',json.dumps(data,separators=(',',':'))).replace('__ENGINE__',(root/'engine/game.js').read_text()).replace('__UI__',(root/'web/ui.js').read_text())
assert '__MAP__' not in html and '__ENGINE__' not in html and '__UI__' not in html
(root/'web/Mundial_War_HTML.html').write_text(html)
(root/'dist').mkdir(exist_ok=True)
(root/'dist/Mundial_War_HTML_0_7_1.html').write_text(html)
runpy.run_path(str(root/'tools/build_place.py'))
print('HTML:',len(html.encode()),'bytes; land:',sum(r.count('1') for r in data['rows']))
